import assert from 'node:assert/strict';
import { test } from 'node:test';
import { attribution } from './attribution-check.mjs';

const SUBJECT = 'docs(log): 2026-11-23\n\n';
const SCISSORS = '# ------------------------ >8 ------------------------\n';

const PASSES = [
  'docs(log): 2026-11-23\n',
  `${SUBJECT}A body line.\n`,
  'fix: the hook refuses a line generated with claude code\n',
  `${SUBJECT}A body sentence that names generated by claude code in its middle.\n`,
  `${SUBJECT}A session line, Claude-Session: x, stays in a sentence.\n`,
  `${SUBJECT}${SCISSORS}+Co-Authored-By: Claude <noreply@anthropic.com>\n`,
];

const REFUSES = [
  `${SUBJECT}Co-Authored-By: Claude <noreply@anthropic.com>\n`,
  `${SUBJECT}co-authored-by: A Person <a@example.com>\n`,
  `${SUBJECT}Claude-Session: https://claude.ai/code/session_x\n`,
  `${SUBJECT}CLAUDE-SESSION: x\n`,
  `${SUBJECT}🤖 Generated with [Claude Code](https://claude.com/claude-code)\n`,
  `${SUBJECT}generated with claude code\n`,
  `${SUBJECT}Generated by Claude Code\n`,
  `${SUBJECT}_Generated by [Claude Code](https://claude.ai/code)_\n`,
  `${SUBJECT}- GENERATED BY CLAUDE CODE\n`,
];

for (const message of PASSES) {
  test(`passes: ${JSON.stringify(message)}`, () => assert.equal(attribution(message), null));
}

for (const message of REFUSES) {
  test(`refuses: ${JSON.stringify(message)}`, () => assert.notEqual(attribution(message), null));
}

test('names the line it refuses', () => {
  assert.equal(attribution(`${SUBJECT}Claude-Session: x\r\n`), 'Claude-Session: x');
});
